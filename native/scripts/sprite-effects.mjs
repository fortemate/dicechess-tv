// Joins the game's sound effects into one file, an audio sprite (#374).
//
//   node scripts/sprite-effects.mjs
//
// On a Fire TV Stick with OS build 2602000051520, a player given a second clip
// now and then hung the app, a player kept after it had played kept the device
// busy, and a fresh player for every cue left more and more behind it until the
// system closed the app. Amazon's advice for games is to join the effects into
// one file and play each by its offset and length; then three players, one for
// each channel, load that file once and are never given another.
//
// Each clip is decoded to 44.1 kHz stereo and laid after GAP_SECONDS of silence,
// with the same silence after the last, so a pause that comes late is still
// silent. The sprite is encoded as constant-bitrate MP3, whose positions are
// exact to a frame, without the Xing frame that would tell a decoder to drop
// the codec's delay: no player is known to read it, so the table counts the
// delay into every start instead. Needs ffmpeg on the PATH. Writes:
//
// - sprite/effects.mp3, the sprite;
// - sprite/sprite.lock.json, its digest and those of the files it was made from;
// - src/effectSprite.ts, where each file's clip starts and how long it lasts.
//
// Run it again whenever sounds/sounds.lock.json changes: a test fails until the
// sprite was made from the files the lock pins.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { byteOrder, sha256 } from './vendor-lib.mjs';

const native = join(dirname(fileURLToPath(import.meta.url)), '..');
const RATE = 44_100;
const CHANNELS = 2;
const FRAME = 2 * CHANNELS;
export const GAP_SECONDS = 2;
// What LAME puts before the first sample (576) and what an MP3 decoder adds to
// it (529): where each clip is heard when the whole file is decoded. Checked by
// decoding the sprite: every clip lines up with its source at this offset.
const CODEC_DELAY = 576 + 529;

const lock = JSON.parse(
  readFileSync(join(native, 'sounds/sounds.lock.json'), 'utf8'),
);
const sources = [];
for (const [pack, { files }] of Object.entries(lock.packs))
  for (const [name, { sha256: pinned }] of Object.entries(files)) {
    if (!name.endsWith('.mp3')) continue;
    const bytes = readFileSync(join(native, 'sounds', pack, name));
    if (sha256(bytes) !== pinned)
      throw new Error(`sounds/${pack}/${name} no longer matches its lock`);
    sources.push({ file: `${pack}/${name}`, sha256: pinned });
  }
sources.sort((a, b) => byteOrder(a.file, b.file));

const decode = (file) =>
  execFileSync(
    'ffmpeg',
    [
      '-v',
      'error',
      '-i',
      join(native, 'sounds', file),
      '-f',
      's16le',
      '-ar',
      String(RATE),
      '-ac',
      String(CHANNELS),
      '-',
    ],
    { maxBuffer: 64 * 1024 * 1024 },
  );

const gap = Buffer.alloc(GAP_SECONDS * RATE * FRAME);
const parts = [gap];
const clips = {};
let at = gap.length;
for (const { file } of sources) {
  const pcm = decode(file);
  clips[file] = {
    start: Number(((at / FRAME + CODEC_DELAY) / RATE).toFixed(4)),
    seconds: Number((pcm.length / FRAME / RATE).toFixed(4)),
  };
  parts.push(pcm, gap);
  at += pcm.length + gap.length;
}

const mp3 = execFileSync(
  'ffmpeg',
  [
    '-v',
    'error',
    '-f',
    's16le',
    '-ar',
    String(RATE),
    '-ac',
    String(CHANNELS),
    '-i',
    '-',
    '-c:a',
    'libmp3lame',
    '-b:a',
    '128k',
    '-write_xing',
    '0',
    '-f',
    'mp3',
    '-',
  ],
  { input: Buffer.concat(parts), maxBuffer: 64 * 1024 * 1024 },
);

mkdirSync(join(native, 'sprite'), { recursive: true });
writeFileSync(join(native, 'sprite/effects.mp3'), mp3);
writeFileSync(
  join(native, 'sprite/sprite.lock.json'),
  JSON.stringify(
    {
      file: 'effects.mp3',
      sha256: sha256(mp3),
      gapSeconds: GAP_SECONDS,
      sources: Object.fromEntries(
        sources.map(({ file, sha256: digest }) => [file, digest]),
      ),
    },
    null,
    2,
  ) + '\n',
);

const rows = Object.entries(clips)
  .map(
    ([file, { start, seconds }]) =>
      `  '${file}': { start: ${start}, seconds: ${seconds} },`,
  )
  .join('\n');
writeFileSync(
  join(native, 'src/effectSprite.ts'),
  `// Generated by scripts/sprite-effects.mjs from sounds/sounds.lock.json. Do not edit.
//
// The sound effects joined into one file (#374): where each vendored file's clip
// starts in it and how long it lasts, in seconds. Each clip has ${GAP_SECONDS} s of
// silence before and after it.
export const EFFECT_SPRITE = 'effects.mp3';

export const EFFECT_CLIPS: Readonly<
  Record<string, { start: number; seconds: number }>
> = {
${rows}
};
`,
);
console.log(
  `sprite: ${sources.length} clips, ${(at / FRAME / RATE).toFixed(1)} s, ${mp3.length} bytes -> sprite/effects.mp3`,
);
